// @effect-diagnostics nodeBuiltinImport:off
// @effect-diagnostics globalDate:off
// @effect-diagnostics cryptoRandomUUID:off
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { dirname, isAbsolute, join, resolve } from "node:path";

export type InstructionScope = "global" | "project";
export type InstructionKind = "sync" | "optional";
export type InstructionProvider = "codex" | "claude" | "opencode" | "cursor" | "custom";

export interface InstructionSyncTarget {
  readonly provider: InstructionProvider;
  readonly scope: InstructionScope;
  readonly projectId?: string;
  /** Project workspace root, required for project-scoped targets. */
  readonly workspaceRoot?: string;
  /** Overrides the provider default path. */
  readonly path?: string;
  readonly filename?: string;
}

export interface InstructionFile {
  readonly id: string;
  readonly kind: InstructionKind;
  readonly scope: InstructionScope;
  readonly projectId?: string;
  readonly title: string;
  readonly filename?: string;
  readonly content: string;
  readonly revision: number;
  readonly updatedAt: string;
  readonly updatedBy?: string;
}

export interface InstructionSync {
  readonly id: string;
  readonly fileId: string;
  readonly targets: ReadonlyArray<InstructionSyncTarget>;
  readonly updatedAt: string;
}

export interface InstructionTargetStatus {
  readonly path: string;
  readonly exists: boolean;
  readonly drift: boolean;
  readonly lastWrittenHash: string;
}

export interface InstructionStoreSnapshot {
  readonly version: 1;
  readonly files: ReadonlyArray<InstructionFile>;
  readonly syncs: ReadonlyArray<InstructionSync>;
  readonly threadAttachments: Readonly<Record<string, ReadonlyArray<string>>>;
  readonly targets: Readonly<Record<string, ReadonlyArray<InstructionTargetStatus>>>;
}

interface StoreIndex {
  version: 1;
  files: InstructionFile[];
  syncs: InstructionSync[];
  threadAttachments: Record<string, string[]>;
  written: Record<string, Record<string, string>>;
}

const DEFAULT_PATHS: Record<
  Exclude<InstructionProvider, "custom">,
  { global: string; project: string }
> = {
  codex: { global: ".codex/AGENTS.md", project: "AGENTS.md" },
  claude: { global: ".claude/CLAUDE.md", project: "CLAUDE.md" },
  opencode: { global: ".config/opencode/AGENTS.md", project: "AGENTS.md" },
  cursor: { global: ".cursor/AGENTS.md", project: "AGENTS.md" },
};

export class InstructionConflictError extends Error {
  readonly id: string;
  readonly expectedRevision: number;
  readonly currentRevision: number;

  constructor(id: string, expectedRevision: number, currentRevision: number) {
    super(
      `Instruction file ${id} changed: expected revision ${expectedRevision}, current ${currentRevision}.`,
    );
    this.id = id;
    this.expectedRevision = expectedRevision;
    this.currentRevision = currentRevision;
  }
}

export class InstructionNotFoundError extends Error {
  readonly id: string;

  constructor(id: string) {
    super(`Instruction file ${id} does not exist.`);
    this.id = id;
  }
}

function emptyIndex(): StoreIndex {
  return { version: 1, files: [], syncs: [], threadAttachments: {}, written: {} };
}

function sha256(text: string): string {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

function generated(content: string, file: InstructionFile): string {
  return [
    `<!-- generated by T3 Code from instruction "${file.title}" (${file.id}, revision ${file.revision}).`,
    "     Edit it in T3; local changes are overwritten on the next sync. -->",
    content,
    "",
  ].join("\n");
}

export class InstructionStore {
  private readonly root: string;
  private readonly home: string;
  private readonly indexPath: string;
  private cached: StoreIndex | undefined;

  constructor(root: string, home: string = homedir()) {
    this.root = root;
    this.home = home;
    this.indexPath = join(root, "index.json");
  }

  private load(): StoreIndex {
    if (this.cached !== undefined) return this.cached;
    if (!existsSync(this.indexPath)) {
      this.cached = emptyIndex();
      return this.cached;
    }
    const parsed = JSON.parse(readFileSync(this.indexPath, "utf8")) as Partial<StoreIndex>;
    this.cached = {
      version: 1,
      files: Array.isArray(parsed.files) ? parsed.files : [],
      syncs: Array.isArray(parsed.syncs) ? parsed.syncs : [],
      threadAttachments:
        parsed.threadAttachments !== undefined && typeof parsed.threadAttachments === "object"
          ? parsed.threadAttachments
          : {},
      written:
        parsed.written !== undefined && typeof parsed.written === "object" ? parsed.written : {},
    };
    return this.cached;
  }

  private save(index: StoreIndex): void {
    mkdirSync(this.root, { recursive: true });
    const temporary = `${this.indexPath}.${process.pid}.tmp`;
    writeFileSync(temporary, `${JSON.stringify(index, null, 2)}\n`, "utf8");
    renameSync(temporary, this.indexPath);
    this.cached = index;
  }

  private materialize(index: StoreIndex, file: InstructionFile): void {
    const sync = index.syncs.find((candidate) => candidate.fileId === file.id);
    if (sync === undefined) return;
    const written = (index.written[file.id] ??= {});
    for (const target of sync.targets) {
      const path = this.resolveTarget(target);
      if (path === null) continue;
      const body = generated(file.content, file);
      mkdirSync(dirname(path), { recursive: true });
      const temporary = `${path}.${process.pid}.tmp`;
      writeFileSync(temporary, body, "utf8");
      renameSync(temporary, path);
      written[path] = sha256(body);
    }
  }

  private resolveTarget(target: InstructionSyncTarget): string | null {
    if (target.path !== undefined) {
      return isAbsolute(target.path) ? target.path : resolve(this.home, target.path);
    }
    if (target.provider === "custom") return null;
    if (target.scope === "global") {
      return join(this.home, DEFAULT_PATHS[target.provider].global);
    }
    if (target.workspaceRoot === undefined) return null;
    const filename = target.filename ?? DEFAULT_PATHS[target.provider].project;
    return join(target.workspaceRoot, filename);
  }

  snapshot(): InstructionStoreSnapshot {
    const index = this.load();
    const targets: Record<string, InstructionTargetStatus[]> = {};
    for (const file of index.files) {
      const sync = index.syncs.find((candidate) => candidate.fileId === file.id);
      if (sync === undefined) {
        targets[file.id] = [];
        continue;
      }
      const written = index.written[file.id] ?? {};
      targets[file.id] = sync.targets.flatMap((target) => {
        const path = this.resolveTarget(target);
        if (path === null) return [];
        const exists = existsSync(path);
        const actual = exists ? sha256(readFileSync(path, "utf8")) : "";
        const lastWrittenHash = written[path] ?? "";
        return [
          {
            path,
            exists,
            drift: exists && lastWrittenHash !== "" && actual !== lastWrittenHash,
            lastWrittenHash,
          },
        ];
      });
    }
    return {
      version: 1,
      files: index.files,
      syncs: index.syncs,
      threadAttachments: index.threadAttachments,
      targets,
    };
  }

  putFile(input: {
    readonly id?: string;
    readonly kind?: InstructionKind;
    readonly scope?: InstructionScope;
    readonly projectId?: string;
    readonly title: string;
    readonly filename?: string;
    readonly content: string;
    readonly expectedRevision?: number;
    readonly updatedBy?: string;
  }): InstructionFile {
    const index = this.load();
    const existing =
      input.id === undefined ? undefined : index.files.find((file) => file.id === input.id);
    if (existing !== undefined && input.expectedRevision !== undefined) {
      if (existing.revision !== input.expectedRevision) {
        throw new InstructionConflictError(
          existing.id,
          input.expectedRevision,
          existing.revision,
        );
      }
    }
    const now = new Date().toISOString();
    const projectId = input.projectId ?? existing?.projectId;
    const filename = input.filename ?? existing?.filename;
    const file: InstructionFile = {
      id: input.id ?? `ins_${crypto.randomUUID().slice(0, 12)}`,
      kind: input.kind ?? existing?.kind ?? "sync",
      scope: input.scope ?? existing?.scope ?? "global",
      title: input.title,
      content: input.content,
      revision: (existing?.revision ?? 0) + 1,
      updatedAt: now,
      ...(projectId === undefined ? {} : { projectId }),
      ...(filename === undefined ? {} : { filename }),
      ...(input.updatedBy === undefined ? {} : { updatedBy: input.updatedBy }),
    };
    const files = existing === undefined
      ? [...index.files, file]
      : index.files.map((candidate) => (candidate.id === file.id ? file : candidate));
    const next: StoreIndex = { ...index, files };
    this.materialize(next, file);
    this.save(next);
    return file;
  }

  setSync(input: {
    readonly id?: string;
    readonly fileId: string;
    readonly targets: ReadonlyArray<InstructionSyncTarget>;
  }): InstructionSync {
    const index = this.load();
    const file = index.files.find((candidate) => candidate.id === input.fileId);
    if (file === undefined) throw new InstructionNotFoundError(input.fileId);
    const existing =
      input.id === undefined ? undefined : index.syncs.find((sync) => sync.id === input.id);
    const sync: InstructionSync = {
      id: input.id ?? existing?.id ?? `sync_${crypto.randomUUID().slice(0, 12)}`,
      fileId: input.fileId,
      targets: input.targets,
      updatedAt: new Date().toISOString(),
    };
    const syncs = existing === undefined
      ? [...index.syncs, sync]
      : index.syncs.map((candidate) => (candidate.id === sync.id ? sync : candidate));
    const next: StoreIndex = { ...index, syncs };
    this.materialize(next, file);
    this.save(next);
    return sync;
  }

  removeSync(id: string): void {
    const index = this.load();
    this.save({ ...index, syncs: index.syncs.filter((sync) => sync.id !== id) });
  }

  setThreadAttachments(threadId: string, fileIds: ReadonlyArray<string>): ReadonlyArray<string> {
    const index = this.load();
    const known = new Set(index.files.map((file) => file.id));
    const validated = [...new Set(fileIds)].filter((id) => known.has(id));
    this.save({ ...index, threadAttachments: { ...index.threadAttachments, [threadId]: validated } });
    return validated;
  }

  threadAttachments(threadId: string): ReadonlyArray<string> {
    return this.load().threadAttachments[threadId] ?? [];
  }
}
