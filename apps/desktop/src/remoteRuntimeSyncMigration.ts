import { spawn } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, join } from "node:path";

/**
 * Windows Task Scheduler task created as a support workaround for the SSH runtime
 * bootstrap. Its action ran a console program directly, so a console window flashed
 * every time the task fired (every minute on the machines that have it).
 */
export const REMOTE_RUNTIME_SYNC_TASK_NAME = "T3 Remote Runtime Sync";
export const HIDDEN_LAUNCHER_FILE_NAME = "remote-runtime-sync-hidden.vbs";
export const MIGRATED_INTERVAL = "PT15M";

export interface ScheduledTaskAction {
  readonly execute: string;
  readonly arguments?: string;
  readonly workingDirectory?: string;
}

export interface HiddenLauncherPlan {
  /** The script the legacy task ran; the hidden launcher stands in for it. */
  readonly scriptPath: string;
  /** The exact command line the legacy action ran. */
  readonly commandLine: string;
  /** Where the generated launcher belongs. */
  readonly launcherPath: string;
}

const CONSOLE_HOSTS = new Set(["cmd.exe", "cmd", "powershell.exe", "powershell", "pwsh.exe", "pwsh"]);
const HIDDEN_LAUNCHERS = new Set(["wscript.exe", "wscript", "cscript.exe", "cscript"]);

function baseName(value: string): string {
  const normalized = value.trim().replace(/\//g, "\\");
  return normalized.slice(normalized.lastIndexOf("\\") + 1).toLowerCase();
}

function unquote(value: string): string {
  const trimmed = value.trim();
  if (trimmed.length >= 2 && trimmed.startsWith('"') && trimmed.endsWith('"')) {
    return trimmed.slice(1, -1);
  }
  return trimmed;
}

/** `-File "<path>"` inside a PowerShell argument string, if that is how the task runs it. */
function powershellScriptPath(argumentsText: string): string | null {
  const match = /(?:^|\s)-File\s+(?:"([^"]+)"|'([^']+)'|(\S+))/i.exec(argumentsText);
  const value = match?.[1] ?? match?.[2] ?? match?.[3];
  return value === undefined ? null : unquote(value);
}

/**
 * Decides how to keep a legacy sync task working without a console window, or returns
 * `null` when the action is not a shape this migration understands. Unknown shapes are
 * left alone rather than guessed at.
 */
export function planHiddenLauncher(action: ScheduledTaskAction): HiddenLauncherPlan | null {
  const execute = unquote(action.execute);
  const argumentsText = (action.arguments ?? "").trim();
  const host = baseName(execute);
  if (HIDDEN_LAUNCHERS.has(host)) return null;

  if (host === "cmd.exe" || host === "cmd" || host.endsWith(".cmd") || host.endsWith(".bat")) {
    const scriptPath = host.endsWith(".cmd") || host.endsWith(".bat")
      ? execute
      : unquote(argumentsText.replace(/^(?:\/[a-z]+\s+)*/i, ""));
    if (!scriptPath || !isAbsolute(scriptPath)) return null;
    const commandLine = host.endsWith(".cmd") || host.endsWith(".bat")
      ? `cmd.exe /d /s /c ""${scriptPath}"${argumentsText ? ` ${argumentsText}` : ""}"`
      : `"${execute}" ${argumentsText}`.trim();
    return {
      scriptPath,
      commandLine,
      launcherPath: join(dirname(scriptPath), HIDDEN_LAUNCHER_FILE_NAME),
    };
  }

  if (host === "powershell.exe" || host === "powershell" || host === "pwsh.exe" || host === "pwsh") {
    const scriptPath = powershellScriptPath(argumentsText);
    if (!scriptPath || !isAbsolute(scriptPath)) return null;
    return {
      scriptPath,
      commandLine: argumentsText ? `"${execute}" ${argumentsText}` : `"${execute}"`,
      launcherPath: join(dirname(scriptPath), HIDDEN_LAUNCHER_FILE_NAME),
    };
  }

  return null;
}

/** Escapes one command line into a VBScript string literal. */
export function vbsStringLiteral(value: string): string {
  return `"${value.replace(/"/g, '""')}"`;
}

/**
 * The launcher runs the legacy command with window style 0 (hidden) and does not wait,
 * so the task stays fire-and-forget exactly like before. WScript itself has no console.
 */
export function renderHiddenLauncher(plan: HiddenLauncherPlan): string {
  return [
    "' Generated by T3 Code. Runs the remote runtime sync without a console window.",
    "Option Explicit",
    "Dim shell",
    'Set shell = CreateObject("WScript.Shell")',
    `shell.Run ${vbsStringLiteral(plan.commandLine)}, 0, False`,
    "",
  ].join("\r\n");
}

function runPowerShell(script: string): Promise<{ code: number; stdout: string; stderr: string }> {
  return new Promise((resolvePromise, rejectPromise) => {
    const encoded = Buffer.from(script, "utf16le").toString("base64");
    const child = spawn(
      "powershell.exe",
      ["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-EncodedCommand", encoded],
      { windowsHide: true, stdio: ["ignore", "pipe", "pipe"] },
    );
    let stdout = "";
    let stderr = "";
    child.stdout.setEncoding("utf8");
    child.stderr.setEncoding("utf8");
    child.stdout.on("data", (chunk: string) => { stdout += chunk; });
    child.stderr.on("data", (chunk: string) => { stderr += chunk; });
    child.once("error", rejectPromise);
    child.once("close", (code) => resolvePromise({ code: code ?? -1, stdout, stderr }));
  });
}

const QUERY_TASK = `
$ErrorActionPreference = 'Stop'
$task = Get-ScheduledTask -TaskName '${REMOTE_RUNTIME_SYNC_TASK_NAME}' -ErrorAction SilentlyContinue
if ($null -eq $task) { 'null'; exit 0 }
$action = @($task.Actions)[0]
[pscustomobject]@{
  execute = [string]$action.Execute
  arguments = [string]$action.Arguments
  workingDirectory = [string]$action.WorkingDirectory
} | ConvertTo-Json -Compress
`;

function rewriteTaskScript(launcherPath: string): string {
  const escapedLauncher = launcherPath.replace(/'/g, "''");
  return `
$ErrorActionPreference = 'Stop'
$task = Get-ScheduledTask -TaskName '${REMOTE_RUNTIME_SYNC_TASK_NAME}'
$action = New-ScheduledTaskAction -Execute 'wscript.exe' -Argument '//B //Nologo "${escapedLauncher}"'
Set-ScheduledTask -TaskName '${REMOTE_RUNTIME_SYNC_TASK_NAME}' -Action $action | Out-Null
$task = Get-ScheduledTask -TaskName '${REMOTE_RUNTIME_SYNC_TASK_NAME}'
foreach ($trigger in $task.Triggers) {
  if ($null -ne $trigger.Repetition) { $trigger.Repetition.Interval = '${MIGRATED_INTERVAL}' }
}
Set-ScheduledTask -TaskName '${REMOTE_RUNTIME_SYNC_TASK_NAME}' -Trigger $task.Triggers | Out-Null
'ok'
`;
}

export type RemoteRuntimeSyncMigrationStatus = "migrated" | "absent" | "already" | "unsupported";

export interface RemoteRuntimeSyncMigrationResult {
  readonly status: RemoteRuntimeSyncMigrationStatus;
  readonly launcherPath?: string;
  readonly detail?: string;
}

/**
 * Rewrites the support task once. Safe to run at every start: an already migrated task is
 * recognised by its `wscript.exe` action and left untouched.
 */
export async function migrateRemoteRuntimeSyncTask(): Promise<RemoteRuntimeSyncMigrationResult> {
  if (process.platform !== "win32") return { status: "absent", detail: "not windows" };

  const query = await runPowerShell(QUERY_TASK);
  if (query.code !== 0) {
    return { status: "unsupported", detail: query.stderr.trim().slice(0, 300) };
  }
  const raw = query.stdout.trim();
  if (raw === "" || raw === "null") return { status: "absent" };

  let action: ScheduledTaskAction;
  try {
    const parsed = JSON.parse(raw) as Partial<ScheduledTaskAction>;
    action = {
      execute: typeof parsed.execute === "string" ? parsed.execute : "",
      arguments: typeof parsed.arguments === "string" ? parsed.arguments : "",
      workingDirectory: typeof parsed.workingDirectory === "string" ? parsed.workingDirectory : "",
    };
  } catch {
    return { status: "unsupported", detail: "task action is not JSON" };
  }

  if (baseName(action.execute) === "wscript.exe" || baseName(action.execute) === "wscript") {
    return { status: "already" };
  }

  const plan = planHiddenLauncher(action);
  if (plan === null) return { status: "unsupported", detail: `unrecognised action: ${action.execute}` };

  await mkdir(dirname(plan.launcherPath), { recursive: true });
  await writeFile(plan.launcherPath, renderHiddenLauncher(plan), "utf8");

  const rewrite = await runPowerShell(rewriteTaskScript(plan.launcherPath));
  if (rewrite.code !== 0 || rewrite.stdout.trim() !== "ok") {
    return { status: "unsupported", detail: rewrite.stderr.trim().slice(0, 300) };
  }
  return { status: "migrated", launcherPath: plan.launcherPath };
}
